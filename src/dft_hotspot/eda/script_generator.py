"""
EDA Script Generator for Yosys and OpenROAD Flow Orchestration.
Supports both standalone OpenROAD scripts and OpenROAD-flow-scripts (ORFS) configurations.
"""

from pathlib import Path
from typing import Dict, Any, List


class ScriptGenerator:
    """Generates synthesis and physical design Tcl/Makefile scripts from flow config."""

    @staticmethod
    def _resolve_pdk_path(pdk_path_str: str, output_script_path: Path) -> str:
        p_path = Path(pdk_path_str)
        if not p_path.is_absolute():
            ws_root = output_script_path.resolve()
            for parent in ws_root.parents:
                if (parent / "configs").exists() or (parent / "pyproject.toml").exists():
                    ws_root = parent
                    break
            else:
                ws_root = Path.cwd()
            p_path = (ws_root / pdk_path_str).resolve()
        return p_path.as_posix()

    @classmethod
    def generate_yosys_synth_tcl(cls, cfg: Dict[str, Any], output_path: Path) -> Path:
        """Generates Yosys synthesis Tcl script for openroad_standalone backend."""
        design = cfg.get("design", {})
        pdk = cfg.get("pdk", {})

        top_module = design.get("top_module", "top")
        liberty_file = pdk.get("liberty_file", "")
        rtl_files = design.get("rtl_files", [])

        liberty_abs = cls._resolve_pdk_path(liberty_file, output_path)

        lines = [
            "# ==================================================================",
            "# Yosys Synthesis Script (Auto-generated by dft_hotspot.eda)",
            f"# Design: {top_module}",
            "# ==================================================================",
            "",
            "# Read Liberty library",
            f"read_liberty -lib {liberty_abs}",
            "",
            "# Read Verilog RTL design files",
        ]

        for rtl in rtl_files:
            rtl_name = Path(rtl).name
            lines.append(f"read_verilog ../rtl/{rtl_name}")

        lines.extend([
            "",
            "# Elaborate design hierarchy",
            f"hierarchy -check -top {top_module}",
            "",
            "# Generic synthesis",
            f"synth -top {top_module}",
            "",
            "# Technology mapping to target Liberty cell library",
            f"dfflibmap -liberty {liberty_abs}",
            f"abc -liberty {liberty_abs}",
            "clean",
            "",
            "# Output netlist and report",
            f"write_verilog -noattr synth_{top_module}.v",
            f"stat -liberty {liberty_abs}",
            ""
        ])

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text("\n".join(lines), encoding="utf-8")
        return output_path

    @classmethod
    def generate_openroad_tcl(cls, cfg: Dict[str, Any], output_path: Path) -> Path:
        """Generates OpenROAD floorplan, place, and route script for standalone backend."""
        design = cfg.get("design", {})
        pdk = cfg.get("pdk", {})
        flow = cfg.get("flow", {})

        top_module = design.get("top_module", "top")
        tech_lef = pdk.get("tech_lef", "")
        stdcell_lef = pdk.get("stdcell_lef", "")
        liberty_file = pdk.get("liberty_file", "")
        site = pdk.get("site", "FreePDK45")

        tech_lef_abs = cls._resolve_pdk_path(tech_lef, output_path)
        stdcell_lef_abs = cls._resolve_pdk_path(stdcell_lef, output_path)
        liberty_abs = cls._resolve_pdk_path(liberty_file, output_path)

        tracks_file = pdk.get("tracks_file")
        tracks_abs = cls._resolve_pdk_path(tracks_file, output_path) if tracks_file else None

        die_area = flow.get("die_area", "0 0 100 100")
        core_area = flow.get("core_area", "10 10 90 90")
        util = flow.get("target_utilization", 0.60)
        clock_port = design.get("clock_port", "clk")
        clock_period = design.get("clock_period", 10.0)
        hor_layer = pdk.get("pin_horizontal_layer", flow.get("pin_horizontal_layer", "metal5"))
        ver_layer = pdk.get("pin_vertical_layer", flow.get("pin_vertical_layer", "metal6"))

        lines = [
            "# ==================================================================",
            "# OpenROAD Physical Design Script (Auto-generated by dft_hotspot.eda)",
            f"# Design: {top_module}",
            "# ==================================================================",
            "",
            "# Read Technology & Macro LEF files",
            f"read_lef {tech_lef_abs}",
            f"read_lef {stdcell_lef_abs}",
            "",
            "# Read Liberty library",
            f"read_liberty {liberty_abs}",
            "",
            "# Read synthesized netlist",
            f"read_verilog synth_{top_module}.v",
            f"link_design {top_module}",
            "",
            "# Create timing clock constraint",
            f"create_clock -name {clock_port} -period {clock_period} [get_ports {clock_port}]",
            "",
            "# Initialize floorplan",
            f"initialize_floorplan -die_area {{{die_area}}} -core_area {{{core_area}}} -site {site}",
        ]

        if tracks_abs:
            lines.append(f"source {tracks_abs}")

        lines.extend([
            f"place_pins -hor_layers {hor_layer} -ver_layers {ver_layer}",
            "",
            "# Global & Detailed Placement",
            f"global_placement -density {util}",
            "detailed_placement",
            "",
            "# Clock Tree Synthesis (CTS)",
            "clock_tree_synthesis",
            "detailed_placement",
            "",
            "# Global & Detailed Routing",
            "global_route",
            "detailed_route",
            "",
            "# Export final DEF / GDS / ODB",
            f"write_def {top_module}_final.def",
            f"write_db {top_module}_final.odb",
            "report_checks -path_delay min_max",
            "report_wns",
            "report_tns",
            ""
        ])

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text("\n".join(lines), encoding="utf-8")
        return output_path

    @staticmethod
    def generate_orfs_config(cfg: Dict[str, Any], output_path: Path) -> Path:
        """Generates OpenROAD-flow-scripts (ORFS) config.mk file."""
        design = cfg.get("design", {})
        pdk = cfg.get("pdk", {})
        flow = cfg.get("flow", {})

        top_module = design.get("top_module", "top")
        pdk_name = pdk.get("name", "nangate45")

        lines = [
            "# ==================================================================",
            "# OpenROAD-flow-scripts (ORFS) Makefile Config",
            "# Auto-generated by dft_hotspot.eda",
            "# ==================================================================",
            f"DESIGN_NAME = {top_module}",
            f"PLATFORM    = {pdk_name}",
            "VERILOG_FILES = $(sort $(wildcard ../rtl/*.v))",
            "SDC_FILE      = ./constraint.sdc",
            f"CORE_UTILIZATION = {int(flow.get('target_utilization', 0.60) * 100)}",
            f"DIE_AREA      = {flow.get('die_area', '0 0 100 100')}",
            f"CORE_AREA     = {flow.get('core_area', '10 10 90 90')}",
            ""
        ]

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text("\n".join(lines), encoding="utf-8")
        return output_path
